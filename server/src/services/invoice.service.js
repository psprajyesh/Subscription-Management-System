import { Counter, Invoice, Settings } from "../models/index.js";
import { addDaysUTC } from "../utils/dates.js";
import { calculateCharge, isDiscountApplicable } from "./billing.service.js";

function padSequence(sequence) {
  return String(sequence).padStart(4, "0");
}

async function buildInvoiceNumber(settings, issuedAt) {
  const sequence = await Counter.next("invoice");
  const prefix = (settings?.invoicePrefix || "INV").toUpperCase();
  return `${prefix}-${issuedAt.getUTCFullYear()}-${padSequence(sequence)}`;
}

/**
 * Creates the one renewal invoice for a subscription period.
 *
 * Idempotency is enforced twice:
 *  - an explicit lookup for an invoice already issued for this period, and
 *  - a partial unique index on (subscription, billingPeriodStart).
 *
 * The second guard also serialises concurrent workers that race past the
 * lookup. No payment is created here; collection belongs to a later phase.
 */
export async function createRenewalInvoice({
  subscription,
  plan = null,
  periodStart,
  periodEnd,
  issuedAt = new Date(),
}) {
  const discountApplied = isDiscountApplicable(subscription, issuedAt);
  const existing = await Invoice.findOne({
    subscription: subscription._id,
    billingPeriodStart: periodStart,
  });

  if (existing) {
    return { invoice: existing, created: false, discountApplied };
  }

  const settings = await Settings.getSingleton();
  const taxRate = subscription.taxRateBasisPoints ?? 0;

  const amounts = calculateCharge({
    priceMinor: subscription.priceMinor,
    quantity: subscription.quantity,
    discountType: discountApplied ? subscription.discountType : null,
    discountValue: discountApplied ? subscription.discountValue : 0,
    fraction: 1,
    taxRateBasisPoints: taxRate,
  });

  const billingCycle = subscription.billingCycle || plan?.billingCycle || "monthly";
  const invoiceNumber = await buildInvoiceNumber(settings, issuedAt);
  const lineAmount = subscription.priceMinor * subscription.quantity;

  try {
    const invoice = await Invoice.create({
      invoiceNumber,
      customer: subscription.customer,
      subscription: subscription._id,
      billingPeriodStart: periodStart,
      billingPeriodEnd: periodEnd,
      items: [
        {
          description: `${plan?.name ?? "Subscription"} plan (${billingCycle})`,
          quantity: subscription.quantity,
          unitAmountMinor: subscription.priceMinor,
          amountMinor: lineAmount,
        },
      ],
      subtotalMinor: amounts.grossMinor,
      discountMinor: amounts.discountMinor,
      taxMinor: amounts.taxMinor,
      totalMinor: amounts.totalMinor,
      currency: subscription.currency || "INR",
      status: "open",
      issueDate: issuedAt,
      dueDate: addDaysUTC(issuedAt, settings.invoiceDueDays ?? 7),
      notes: "Renewal invoice generated by Brightloop.",
    });

    return { invoice, created: true, discountApplied };
  } catch (error) {
    if (error?.code === 11000) {
      const raced = await Invoice.findOne({
        subscription: subscription._id,
        billingPeriodStart: periodStart,
      });

      if (raced) {
        return { invoice: raced, created: false, discountApplied };
      }
    }

    throw error;
  }
}

export default createRenewalInvoice;
